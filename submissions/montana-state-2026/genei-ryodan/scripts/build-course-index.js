#!/usr/bin/env node
/* ============================================================
   Mathub — light class index for on-demand loading
   The app shell no longer ships every class's notes, questions and
   flashcards. This script reads the full data files and writes
   assets/courses-index.js: for each class, the small fields the
   landing page, Today, search, the GPA calculator and the calendar
   need (name, syllabus facts, exams, calendar, unit and section
   titles, quiz topic names, counts), plus the list of files that
   App.loadCourse() fetches when the class is opened.
   Run from calc1/ whenever a *-data.js or *-quiz.js file changes:
     node scripts/build-course-index.js
   ============================================================ */
'use strict';
const fs = require('fs'); const path = require('path');
const ROOT = path.resolve(__dirname, '..');
global.window = {};
['calc-data', 'calc-quiz', 'physics-data', 'physics-quiz', 'precalc-data', 'precalc-quiz', 'writ-data', 'csci-data', 'csci-quiz', 'biob-data', 'biob-quiz', 'kin-data', 'kin-quiz', 'psyx-data', 'psyx-quiz'].forEach(f => require(path.join(ROOT, 'assets', f + '.js')));
const Courses = window.Courses;
/* the scripts each class needs, in load order (shared files are fetched once) */
const FILES = {
  calc: ['calc-data', 'calc-quiz', 'calc-tools'],
  physics: ['physics-data', 'physics-quiz', 'physics-tools'],
  precalc: ['precalc-data', 'precalc-quiz', 'calc-tools', 'precalc-tools'],   // the grapher lives in calc-tools
  writ: ['writ-data', 'phonetics-data', 'phonetics'],
  csci: ['csci-data', 'csci-quiz', 'pylab'],
  biob: ['biob-data', 'biob-quiz'],
  kin: ['kin-data', 'kin-quiz'],
  psyx: ['psyx-data', 'psyx-quiz']
};
const LIGHT = ['id', 'code', 'name', 'short', 'term', 'tagline', 'kind', 'quizNote', 'COURSE', 'EXAMS', 'CALENDAR', 'CALENDAR_NOTE', 'RECURRING', 'SEMESTER', 'VARIANTS', 'UNITS', 'NAV'];
const out = {};
for (const [id, C] of Object.entries(Courses)) {
  const files = FILES[id]; if (!files) { console.warn('No file list for class', id); continue; }
  for (const f of files) if (!fs.existsSync(path.join(ROOT, 'assets', f + '.js'))) throw new Error(`Missing assets/${f}.js for class ${id}`);
  const S = {}; LIGHT.forEach(k => { if (C[k] !== undefined) S[k] = C[k]; });
  S.SECTIONS = (C.SECTIONS || []).map(s => ({ id: s.id, label: s.label, title: s.title, unit: s.unit }));
  if (C.READINGS) S.READINGS = C.READINGS.map(r => ({ id: r.id, title: r.title, author: r.author }));
  const T = C.quiz && C.quiz.TOPICS; if (T) { S.hasQuiz = true; S.quizTopics = {}; Object.entries(T).forEach(([t, v]) => { S.quizTopics[t] = { label: v.label, sec: v.sec, unit: v.unit }; }); }
  S.sectionCount = S.SECTIONS.length; S.flashcardCount = (C.FLASHCARDS || []).length; S.formulaCount = (C.FORMULAS || []).reduce((n, g) => n + (g.items || []).length, 0);
  S.files = files; S.stub = true;
  out[id] = S;
}
const js = `/* ============================================================
   Mathub — class index (generated by scripts/build-course-index.js)
   Do not edit by hand: run  node scripts/build-course-index.js
   Each class here is a light stub. App.loadCourse(id) fetches the
   files listed under "files" the first time the class is opened;
   they merge the full notes, questions and flashcards into the
   same object with Object.assign.
   ============================================================ */
(function (g) {
  'use strict';
  g.Courses = g.Courses || {};
  const IX = ${JSON.stringify(out)};
  for (const id in IX) g.Courses[id] = Object.assign(g.Courses[id] || {}, IX[id]);
})(typeof window !== 'undefined' ? window : globalThis);
`;
fs.writeFileSync(path.join(ROOT, 'assets', 'courses-index.js'), js);
const kb = n => (n / 1024).toFixed(1) + ' KB';
console.log(`assets/courses-index.js written: ${kb(js.length)} for ${Object.keys(out).length} classes`);
for (const [id, S] of Object.entries(out)) console.log(`  ${id.padEnd(8)} ${String(S.sectionCount).padStart(3)} topics ${String(S.flashcardCount).padStart(4)} cards ${S.hasQuiz ? Object.keys(S.quizTopics).length + ' quiz topics' : 'no quiz'} · files: ${S.files.join(', ')} (${kb(S.files.reduce((n, f) => n + fs.statSync(path.join(ROOT, 'assets', f + '.js')).size, 0))})`);
